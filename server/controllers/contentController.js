const prisma = require("../config/prisma");


const generateContent = async (req, res) => {

    try {

        const {
            businessName,
            contentType,
            tone
        } = req.body;


        // Fake AI response for BrandOS MVP
        const response = {

            output_text: `
${contentType} for ${businessName}

Tone: ${tone}

Welcome to ${businessName}!

Here are some marketing ideas:

1. Create engaging social media posts.
2. Share customer success stories.
3. Highlight your unique products and services.
4. Build a strong relationship with your audience.

This content was generated by BrandOS AI.
            `.trim()

        };


        const savedContent = await prisma.content.create({

            data: {

                type: contentType,

                title: `${businessName} ${contentType}`,

                body: response.output_text,

                userId: req.user.id

            }

        });


        res.json({

            content: savedContent.body

        });


    } catch (error) {

        console.log("========== CONTENT ERROR ==========");
        console.log(error);
        console.log("===================================");

        res.status(500).json({

            message: error.message

        });

    }

};


const getHistory = async (req, res) => {

    try {

        const history = await prisma.content.findMany({

            where: {

                userId: req.user.id

            },

            orderBy: {

                createdAt: "desc"

            }

        });


        res.json(history);


    } catch (error) {

        res.status(500).json({

            message: error.message

        });

    }

};


const updateContent = async (req, res) => {

    try {

        const contentId = Number(req.params.id);

        const { body } = req.body;


        const existingContent = await prisma.content.findFirst({

            where: {

                id: contentId,

                userId: req.user.id

            }

        });


        if (!existingContent) {

            return res.status(404).json({

                message: "Content not found"

            });

        }


        const updatedContent = await prisma.content.update({

            where: {

                id: contentId

            },

            data: {

                body

            }

        });


        res.json(updatedContent);


    } catch (error) {

        res.status(500).json({

            message: error.message

        });

    }

};


