const getContentStats = async (req, res) => {

    try {

        const contents = await prisma.content.findMany({

            where: {

                userId: req.user.id

            },

            include: {

                seoAnalysis: true,

                toneAnalysis: true

            }

        });


        const total = contents.length;


        const blogPosts = contents.filter(

            item => item.type === "Blog Post"

        ).length;


        const socialPosts = contents.filter(

            item => item.type === "Social Media Caption"

        ).length;


        const emails = contents.filter(

            item => item.type === "Email Campaign"

        ).length;


        const seoScores = contents

            .filter(item => item.seoAnalysis)

            .map(item => item.seoAnalysis.score);


        const averageSEO = seoScores.length

            ? Math.round(

                seoScores.reduce(
                    (a, b) => a + b,
                    0
                ) / seoScores.length

            )

            : 0;


        const toneConfidence = contents

            .filter(item => item.toneAnalysis)

            .map(item => item.toneAnalysis.confidence);


        const averageToneConfidence = toneConfidence.length

            ? Math.round(

                toneConfidence.reduce(
                    (a, b) => a + b,
                    0
                ) / toneConfidence.length

            )

            : 0;


        res.json({

            total,

            blogPosts,

            socialPosts,

            emails,

            averageSEO,

            averageToneConfidence

        });


    } catch (error) {

        res.status(500).json({

            message: error.message

        });

    }

};


const analyzeSEO = async (req, res) => {

    try {

        const contentId = Number(req.params.id);


        const content = await prisma.content.findFirst({

            where: {

                id: contentId,

                userId: req.user.id

            }

        });


        if (!content) {

            return res.status(404).json({

                message: "Content not found"

            });

        }


        // Fake SEO analysis for BrandOS MVP
        const seoResult = {

            score: 85,

            keywords:
                "marketing, business, audience, brand",

            suggestions:
                "Add more relevant keywords and improve content structure."

        };


        const savedSEO = await prisma.sEOAnalysis.upsert({

            where: {

                contentId: content.id

            },

            update: {

                score: seoResult.score,

                keywords: seoResult.keywords,

                suggestions: seoResult.suggestions

            },

            create: {

                score: seoResult.score,

                keywords: seoResult.keywords,

                suggestions: seoResult.suggestions,

                contentId: content.id

            }

        });


        res.json(savedSEO);


    } catch (error) {

        console.log(error);

        res.status(500).json({

            message: error.message

        });

    }

};


